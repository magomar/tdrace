/// Complete real-world motorsport car model definition.
#[derive(Debug, Clone)]
pub struct RealCarModel {
    pub id: &'static str,
    pub name: &'static str,
    pub manufacturer: &'static str,
    pub year: u16,
    pub module_id: &'static str,
    pub category_name: &'static str,
    pub tier: u8, // 1..=5
    pub bhp: u16,
    pub torque_nm: u16,
    pub weight_kg: u16,
    pub top_speed_kmh: u16,
    pub accel_0_100: f32,
    pub drivetrain: &'static str, // "RWD", "AWD", "FWD", "4WD"
    pub engine_desc: &'static str,
    pub aero_downforce: &'static str,
    pub brakes_desc: &'static str,
    pub history_bio: &'static str,
    /// Normalized performance ratings: (Speed, Accel, Grip, Drift/Agility, Brake, Aero) [0.0..1.0]
    pub stats: (f32, f32, f32, f32, f32, f32),
    pub visual_type: VehicleVisualType,
    pub base_car_choice: CarChoice,
    pub primary_color: Color,
    pub secondary_color: Color,
}

impl RealCarModel {
    /// Checks whether this vehicle is eligible for a race with a required category/tier.
    /// Rule: Selectable iff car.tier <= race_required_tier || dev_mode.
    #[inline]
    pub fn is_eligible_for_race(&self, race_required_tier: u8, dev_mode: bool) -> bool {
        dev_mode || self.tier <= race_required_tier
    }

    /// Returns the high-level motorsport car category for this vehicle model.
    pub fn category(&self) -> tdrace_core::CarCategory {
        match self.module_id {
            "gt" | "gt_challenge" => tdrace_core::CarCategory::Gt,
            "nascar" => tdrace_core::CarCategory::Nascar,
            "rally" => tdrace_core::CarCategory::Rally,
            "kart" => tdrace_core::CarCategory::Kart,
            "extreme_offroad" => tdrace_core::CarCategory::OffRoad,
            "classic" => match self.id {
                "classic_gt" => tdrace_core::CarCategory::Gt,
                "classic_nascar" => tdrace_core::CarCategory::Nascar,
                "classic_rally" => tdrace_core::CarCategory::Rally,
                "classic_kart" => tdrace_core::CarCategory::Kart,
                "classic_offroad" => tdrace_core::CarCategory::OffRoad,
                _ => self.base_car_choice.category(),
            },
            _ => self.base_car_choice.category(),
        }
    }

    /// Derives the customized `CarConfig` matching the physical attributes of this real-world car model.
    pub fn to_car_config(&self) -> tdrace_core::physics::config::CarConfig {
        let mut cfg = self.base_car_choice.config();
        cfg.mass = self.weight_kg as f32;
        cfg.top_speed_mps = (self.top_speed_kmh as f32) / 3.6;

        // Realistic tractive force derived from engine BHP and drivetrain
        let force_per_bhp = match self.module_id {
            "kart" => 38.0,
            "extreme_offroad" if self.tier >= 4 => 14.0,
            _ => 17.5,
        };
        cfg.max_engine_force = (self.bhp as f32) * force_per_bhp;

        match self.drivetrain {
            "FWD" => cfg.drive_bias = 1.0,
            "AWD" | "4WD" => cfg.drive_bias = 0.5,
            _ => cfg.drive_bias = 0.0,
        }

        cfg
    }

    /// Returns the engine sound archetype for this real car model.
    pub fn sound_type(&self) -> EngineSoundType {
        if self.module_id == "classic" {
            match self.id {
                "classic_gt" => EngineSoundType::SportGT,
                "classic_nascar" => EngineSoundType::NascarV8,
                "classic_offroad" => EngineSoundType::SandRailBoxer,
                "classic_kart" => EngineSoundType::Kart125cc,
                "classic_rally" => EngineSoundType::RallyTurbo,
                _ => self.base_car_choice.sound_type(),
            }
        } else {
            match self.module_id {
                "nascar" => EngineSoundType::NascarV8,
                "rally" => EngineSoundType::RallyTurbo,
                "kart" => EngineSoundType::Kart125cc,
                "extreme_offroad" => EngineSoundType::SandRailBoxer,
                "gt" | "gt_challenge" => EngineSoundType::SportGT,
                _ => self.base_car_choice.sound_type(),
            }
        }
    }
}

