/// Complete real-world motorsport car model definition.
#[derive(Debug, Clone)]
pub struct RealCarModel {
    pub id: &'static str,
    pub name: &'static str,
    pub manufacturer: &'static str,
    pub year: u16,
    pub module_id: &'static str,
    pub category_name: &'static str,
    pub tier: u8, // 1..=5
    pub bhp: u16,
    pub torque_nm: u16,
    pub weight_kg: u16,
    pub top_speed_kmh: u16,
    pub accel_0_100: f32,
    pub drivetrain: &'static str, // "RWD", "AWD", "FWD", "4WD"
    pub engine_desc: &'static str,
    pub aero_downforce: &'static str,
    pub brakes_desc: &'static str,
    pub history_bio: &'static str,
    /// Normalized performance ratings: (Speed, Accel, Grip, Drift/Agility, Brake, Aero) [0.0..1.0]
    pub stats: (f32, f32, f32, f32, f32, f32),
    pub visual_type: VehicleVisualType,
    pub base_car_choice: CarChoice,
    pub primary_color: Color,
    pub secondary_color: Color,
}

impl RealCarModel {
    /// Checks whether this vehicle is eligible for a race with a required category/tier.
    /// Rule: Selectable iff car.tier <= race_required_tier || dev_mode.
    #[inline]
    pub fn is_eligible_for_race(&self, race_required_tier: u8, dev_mode: bool) -> bool {
        dev_mode || self.tier <= race_required_tier
    }
}

