/// Helper function to check category eligibility for a race.
/// Rule: A car is eligible iff car.tier <= race_required_tier || dev_mode.
#[inline]
pub fn is_car_eligible(car_tier: u8, race_required_tier: u8, dev_mode: bool) -> bool {
    dev_mode || car_tier <= race_required_tier
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_all_modules_have_5_tiers() {
        for m in ["gt", "nascar", "rally", "extreme_offroad", "kart"] {
            for t in 1..=5 {
                let models = get_models_for_module_and_tier(m, t);
                assert!(
                    !models.is_empty(),
                    "Module {} must have at least 1 authentic model for tier {}",
                    m,
                    t
                );
            }
        }
    }

    #[test]
    fn test_category_eligibility_rule() {
        // In dev mode, any car can race anywhere
        assert!(is_car_eligible(5, 1, true));
        assert!(is_car_eligible(1, 1, true));

        // Normal mode: car tier <= race tier
        assert!(is_car_eligible(1, 1, false));
        assert!(is_car_eligible(1, 2, false));
        assert!(is_car_eligible(2, 2, false));
        assert!(is_car_eligible(3, 5, false));

        // Normal mode: superior tier blocked!
        assert!(!is_car_eligible(2, 1, false));
        assert!(!is_car_eligible(3, 2, false));
        assert!(!is_car_eligible(5, 4, false));
    }
}
