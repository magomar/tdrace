//! Bot behaviour benchmark (spec 046).
//!
//! Runs the spec 046 sample (6 styles x 5 tiers x 4 classic tracks, 10 laps) plus solo line
//! runs, and writes `reports/bot_behaviour_report.md`.

use std::fmt::Write as _;

use tdrace_app::ai::bot_harness::{
    brake_onset_spread_m, lap_spread, line_spread_m, run_harness_race, run_keyboard_reference_race, run_style_grids, sample_bot, HarnessEntry,
    KEYBOARD_REFERENCE_TRACKS,
    StyleGridRun, SAMPLE_TRACKS,
};
use tdrace_app::ai::humanize::find_corners;
use tdrace_app::ai::{DriverTier, DrivingStyle, MistakeKind};
use tdrace_app::catalog::CLASSIC_ARCADE_CARS;

const LAPS: u32 = 10;
const TIERS: [DriverTier; 5] = [DriverTier::Rookie, DriverTier::Amateur, DriverTier::Contender, DriverTier::Pro, DriverTier::Legend];

fn mean(xs: &[f32]) -> f32 {
    if xs.is_empty() { f32::NAN } else { xs.iter().sum::<f32>() / xs.len() as f32 }
}

fn main() {
    let t0 = std::time::Instant::now();
    let runs = run_style_grids(&TIERS, LAPS);
    let mut md = String::new();
    let _ = writeln!(md, "# Bot Behaviour Report (spec 046)\n");
    let _ = writeln!(
        md,
        "Generated by `cargo run -p tdrace-app --release --bin bot_behaviour_benchmark`. Sample: 6 styles x 5 tiers on 4 classic tracks, {LAPS} laps per race, one six-car grid per track and tier. Big mistake = spin (heading > 90 deg off the track direction) or off track > 1 s.\n"
    );

    // Per tier and track.
    let _ = writeln!(md, "## Tiers\n");
    let _ = writeln!(md, "| Track | Tier | Mean flying lap (s) | vs T4 | Lap spread | Mistakes / lap | Spins / lap | Offs / lap | Longest without progress (s) | DNF |");
    let _ = writeln!(md, "|---|---|---|---|---|---|---|---|---|---|");
    for (slug, _) in SAMPLE_TRACKS {
        let track_runs: Vec<&StyleGridRun> = runs.iter().filter(|r| r.track == slug).collect();
        let tier_mean = |tier: DriverTier| {
            let run = track_runs.iter().find(|r| r.tier == tier).unwrap();
            mean(&run.results.iter().filter_map(|c| c.mean_flying_lap()).collect::<Vec<_>>())
        };
        let t4 = tier_mean(DriverTier::Pro);
        for run in &track_runs {
            let laps: f32 = run.results.iter().map(|c| c.lap_times.len() as f32).sum();
            let flying: Vec<f32> = run.results.iter().flat_map(|c| c.lap_times.iter().skip(1).copied()).collect();
            let spread = mean(&run.results.iter().map(|c| lap_spread(&c.lap_times[1.min(c.lap_times.len())..])).collect::<Vec<_>>());
            let sum = |f: &dyn Fn(&tdrace_app::ai::BotDrivingStats) -> u32| run.results.iter().map(|c| f(&c.stats)).sum::<u32>() as f32;
            let m = mean(&flying);
            let _ = writeln!(
                md,
                "| {} | T{} | {:.2} | {:+.1} % | {:.2} % | {:.2} | {:.3} | {:.3} | {:.1} | {} |",
                slug,
                run.tier.to_u8(),
                tier_mean(run.tier),
                (m / t4 - 1.0) * 100.0,
                spread * 100.0,
                sum(&|s| s.total_mistakes()) / laps,
                sum(&|s| s.spins) / laps,
                sum(&|s| s.offs) / laps,
                run.results.iter().map(|c| c.longest_no_progress_s).fold(0.0, f32::max),
                run.results.iter().filter(|c| !c.finished).count(),
            );
        }
    }

    // Per style, all tracks and tiers.
    let _ = writeln!(md, "\n## Styles\n");
    let _ = writeln!(md, "| Style | Mistakes | LateBrake | Overdrive | PowerStab | OverCorrect | Cautious | Spins | Offs | Mistakes / corner clean | Mistakes / corner under pressure |");
    let _ = writeln!(md, "|---|---|---|---|---|---|---|---|---|---|---|");
    for (s, style) in DrivingStyle::ALL.iter().enumerate() {
        let stats: Vec<_> = runs.iter().map(|r| &r.results[s].stats).collect();
        let total: u32 = stats.iter().map(|x| x.total_mistakes()).sum();
        let kind = |k: MistakeKind| stats.iter().map(|x| x.mistakes[k.index()]).sum::<u32>();
        let corners: u32 = stats.iter().map(|x| x.corners).sum();
        let press: u32 = stats.iter().map(|x| x.corners_under_pressure).sum();
        let m_press: u32 = stats.iter().map(|x| x.mistakes_under_pressure).sum();
        let _ = writeln!(
            md,
            "| {:?} | {} | {} | {} | {} | {} | {} | {} | {} | {:.3} | {:.3} |",
            style,
            total,
            kind(MistakeKind::LateBrake),
            kind(MistakeKind::Overdrive),
            kind(MistakeKind::PowerStab),
            kind(MistakeKind::OverCorrect),
            kind(MistakeKind::Cautious),
            stats.iter().map(|x| x.spins).sum::<u32>(),
            stats.iter().map(|x| x.offs).sum::<u32>(),
            (total - m_press) as f32 / (corners - press).max(1) as f32,
            m_press as f32 / press.max(1) as f32,
        );
    }

    // Solo line and braking spread on Classic GP.
    let _ = writeln!(md, "\n## Lines (solo Balanced bot, Classic GP, {LAPS} laps)\n");
    let _ = writeln!(md, "| Tier | Line spread (m) | Brake-onset spread (m) | Lap times (s) |");
    let _ = writeln!(md, "|---|---|---|---|");
    let track = tdrace_core::catalog::official_track("classic", "classic_grand_prix");
    let corners = find_corners(&track.spline);
    let gt = CLASSIC_ARCADE_CARS.iter().find(|c| c.id == "classic_gt").unwrap().to_car_config();
    for tier in TIERS {
        let r = &run_harness_race(&track, vec![HarnessEntry::bot(sample_bot(DrivingStyle::Balanced, tier, 45), gt)], LAPS, LAPS as f32 * 240.0)[0];
        let laps: Vec<String> = r.lap_times.iter().map(|t| format!("{t:.2}")).collect();
        let _ = writeln!(
            md,
            "| T{} | {:.2} | {:.2} | {} |",
            tier.to_u8(),
            line_spread_m(r),
            brake_onset_spread_m(r, &corners, track.spline.total_length()),
            laps.join(", ")
        );
    }

    // Keyboard reference driver against a Tier 1 grid.
    let _ = writeln!(md, "\n## Keyboard reference vs Tier 1 ({LAPS} laps)\n");
    let _ = writeln!(md, "Reference: a T3 Balanced bot with the human layer off, its controls cut to key presses and sent through the Balanced filter and `PlayerHandling`.\n");
    let _ = writeln!(md, "| Track | Reference mean lap (s) | T1 grid mean lap (s) | T1 slowest bot (s) | T1 fastest bot (s) |");
    let _ = writeln!(md, "|---|---|---|---|---|");
    for t in KEYBOARD_REFERENCE_TRACKS {
        let (reference, grid) = run_keyboard_reference_race(t, LAPS);
        let bots: Vec<f32> = grid.iter().filter_map(|c| c.mean_flying_lap()).collect();
        let _ = writeln!(
            md,
            "| {} | {:.2} | {:.2} | {:.2} | {:.2} |",
            SAMPLE_TRACKS[t].0,
            reference.mean_flying_lap().unwrap_or(f32::NAN),
            mean(&bots),
            bots.iter().copied().fold(f32::MIN, f32::max),
            bots.iter().copied().fold(f32::MAX, f32::min)
        );
    }

    std::fs::create_dir_all("reports").expect("create reports dir");
    std::fs::write("reports/bot_behaviour_report.md", &md).expect("write report");
    println!("{md}");
    println!("wrote reports/bot_behaviour_report.md in {:.1} s", t0.elapsed().as_secs_f32());
}
